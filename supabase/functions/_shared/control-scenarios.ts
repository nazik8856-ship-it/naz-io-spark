// Each scenario is a proposed action exactly as the Control System chat would
// hand it to control-engine. `expected` is the verdict the gate SHOULD return.
// `also_acceptable` covers cases where two verdicts are both defensible (e.g.
// a risky-but-in-scope action may come back "modify" instead of "block") — a
// hit there is reported as a soft pass so the report stays honest instead of
// flapping on model wording.
//
