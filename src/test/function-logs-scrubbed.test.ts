// Secrets handling, front 2: the guard that keeps every log path scrubbed. A new edge function that forgets the console scrubber,
// code that writes to the log stream around the console, or an error reporter that loses its scrubbing fails here.
import { describe, it, expect } from "vitest";
import { readdirSync, readFileSync, existsSync } from "node:fs";
import { join } from "node:path";

const FUNCTIONS = join(__dirname, "../../supabase/functions");
const FIRST = 'import "../_shared/redact-console.ts";';
const GENERATED = "// AUTO-GENERATED by @lovable.dev/mcp-js";

const entryPoints = readdirSync(FUNCTIONS, { withFileTypes: true })
  .filter((d) => d.isDirectory() && !d.name.startsWith("_") && existsSync(join(FUNCTIONS, d.name, "index.ts")))
  .map((d) => d.name);

/** Every .ts under supabase/functions except tests. */
function sources(dir = FUNCTIONS): string[] {
  return readdirSync(dir, { withFileTypes: true }).flatMap((d) => {
    const p = join(dir, d.name);
    if (d.isDirectory()) return d.name === "_test-support" ? [] : sources(p);
    return d.name.endsWith(".ts") && !d.name.endsWith("_test.ts") ? [p] : [];
  });
}

describe("function logs: every path goes through the scrubber", () => {
  it("there are edge functions to check", () => {
    expect(entryPoints.length).toBeGreaterThan(80);
  });

  it.each(entryPoints)("%s imports the console scrubber before anything else", (name) => {
    const src = readFileSync(join(FUNCTIONS, name, "index.ts"), "utf8");
    if (src.startsWith(GENERATED)) {
      // Built by the Vite plugin from its source file: the scrubber is bundled in, ahead of the function's own code.
      expect(src.indexOf("installRedactingConsole();"), `${name}: the bundle must start the console scrubber`).toBeGreaterThan(-1);
      expect(src.indexOf("installRedactingConsole();")).toBeLessThan(src.indexOf("defineMcp("));
      return;
    }
    const firstImport = src.split("\n").find((l) => /^\s*import\s/.test(l));
    expect(firstImport?.trim().startsWith(FIRST), `${name}/index.ts: the first import must be ${FIRST}`).toBe(true);
  });

  it("the generated MCP function's source starts the scrubber first, so every rebuild keeps it", () => {
    const src = readFileSync(join(__dirname, "../lib/mcp/index.ts"), "utf8");
    expect(src.split("\n").find((l) => /^\s*import\s/.test(l))?.trim().startsWith('import "../../../supabase/functions/_shared/redact-console.ts";')).toBe(true);
  });

  it("nothing writes to the log stream around the console", () => {
    const offenders = sources().filter((f) => /Deno\.std(out|err)/.test(readFileSync(f, "utf8")));
    expect(offenders).toEqual([]);
  });

  it("the server error reporter scrubs everything it sends", () => {
    const src = readFileSync(join(FUNCTIONS, "_shared/sentry.ts"), "utf8");
    expect(src).toMatch(/sendDefaultPii:\s*false/);
    expect(src).toMatch(/beforeSend:\s*\(event\)\s*=>\s*scrubErrorEvent\(event\)/);
    expect(src).toMatch(/beforeBreadcrumb:\s*\(crumb\)\s*=>\s*scrubErrorEvent\(crumb\)/);
    expect(src).toMatch(/captureException\(redactDeep\(err\)/);
    expect(src).toMatch(/captureMessage\(redactSecrets\(message\)/);
  });

  it("the website error reporter scrubs everything it sends", () => {
    const src = readFileSync(join(__dirname, "../lib/sentry.ts"), "utf8");
    expect(src).toMatch(/sendDefaultPii:\s*false/);
    expect(src).toMatch(/beforeSend:\s*\(event\)\s*=>\s*scrubErrorEvent\(event\)/);
    expect(src).toMatch(/beforeSendTransaction:\s*\(event\)\s*=>\s*scrubErrorEvent\(event\)/);
    expect(src).toMatch(/beforeBreadcrumb:\s*\(crumb\)\s*=>\s*scrubErrorEvent\(crumb\)/);
  });
});
