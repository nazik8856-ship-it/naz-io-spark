// Data encryption, front 1: everything NazAI sends travels encrypted. These checks fail the build when a change would add a plain
// http:// address, let a send to a customer's address follow a redirect (which could carry the data to plain http or another
// host), read a typed-in page without the https-only fetch, or let the two hosting setups drift apart on HTTPS and the
// content security policy.
import { describe, it, expect } from "vitest";
import { readdirSync, readFileSync } from "node:fs";
import { join } from "node:path";

const ROOT = join(__dirname, "../..");
const FUNCTIONS = join(ROOT, "supabase/functions");
const MIGRATIONS = join(ROOT, "supabase/migrations");
const read = (p: string) => readFileSync(join(ROOT, p), "utf8");

function files(dir: string, keep: (name: string) => boolean): string[] {
  return readdirSync(dir, { withFileTypes: true }).flatMap((d) => {
    const p = join(dir, d.name);
    // mcp/ is generated by the build; _test-support/ only runs in tests.
    if (d.isDirectory()) return d.name === "mcp" || d.name === "_test-support" ? [] : files(p, keep);
    return keep(d.name) ? [p] : [];
  });
}

/** Removes comments, so a comment that mentions http:// is not counted as an address. */
const code = (src: string) => src.replace(/^\s*\/\*[\s\S]*?\*\//gm, "").replace(/(^|\s)\/\/.*$/gm, "$1");
const plainHttp = (src: string) => [...src.matchAll(/http:\/\/[^\s"'`)]+/gi)].map((m) => m[0]).filter((u) => !u.startsWith("http://www.w3.org/"));

describe("no plain http addresses", () => {
  it("the edge functions never name an http:// address", () => {
    const found = files(FUNCTIONS, (n) => n.endsWith(".ts") && !n.endsWith("_test.ts"))
      .flatMap((f) => plainHttp(code(readFileSync(f, "utf8"))).map((u) => `${f.slice(ROOT.length + 1)}: ${u}`));
    expect(found).toEqual([]);
  });

  it("the scheduled jobs in migrations call https addresses only", () => {
    const found = files(MIGRATIONS, (n) => n.endsWith(".sql"))
      .filter((f) => /url\s*:=\s*'http:\/\//i.test(readFileSync(f, "utf8")))
      .map((f) => f.slice(ROOT.length + 1));
    expect(found).toEqual([]);
  });

  it("the website talks to Supabase over https", () => {
    expect(read("src/integrations/supabase/client.ts")).toMatch(/SUPABASE_URL\s*=\s*["']https:\/\//);
  });

  it("stored delivery addresses must be https in the database itself", () => {
    const sql = read("supabase/migrations/20261101010000_https_only_addresses.sql");
    for (const c of ["webhooks_url_https", "api_keys_callback_url_https", "external_tools_endpoint_https"]) expect(sql).toContain(c);
  });
});

describe("sends to a customer's address never follow a redirect", () => {
  // Each entry: a file, and the start of the fetch call that sends to an address a customer gave (with their data, a signature or a
  // credential). The call's options must say redirect: "manual".
  const SENDS: [string, string][] = [
    ["supabase/functions/_shared/webhooks.ts", "fetch(hook.url"],
    ["supabase/functions/webhook-retry-sweep/index.ts", "fetch(hook.url"],
    ["supabase/functions/_shared/callback-delegation.ts", "fetch"],
    ["supabase/functions/_shared/outer-control-session.ts", "fetchImpl(tool.endpoint_url"],
    ["supabase/functions/_shared/outer-control-tool-test.ts", "fetchImpl(tool.endpoint_url"],
    ["supabase/functions/_shared/outer-control-mcp.ts", "fetchImpl(ep.url"],
    ["supabase/functions/integration-connect/index.ts", "fetch(shopifyUrl"],
    ["supabase/functions/integration-connect/index.ts", "fetch(wooUrl"],
    ["supabase/functions/integration-connect/index.ts", "fetch(c.webhook_url"],
    ["supabase/functions/integration-sync/index.ts", "fetch(ordersUrl"],
    ["supabase/functions/integration-sync/index.ts", "fetch(productsUrl"],
    ["supabase/functions/integration-sync/index.ts", "fetch(wooUrl"],
  ];

  it.each(SENDS)("%s: %s(…) sets redirect: \"manual\"", (file, call) => {
    const src = code(read(file));
    const at = file.endsWith("callback-delegation.ts") ? src.search(/await (?:deps\.)?fetch\w*\(/) : src.indexOf(call);
    expect(at, `${call} not found`).toBeGreaterThanOrEqual(0);
    // The options object closes within a few lines of the call.
    expect(src.slice(at, at + 600)).toMatch(/redirect:\s*"manual"/);
  });

  it("the agents' http_post tool does not follow redirects", () => {
    for (const f of ["supabase/functions/agent-runtime/index.ts", "supabase/functions/agent-approval/index.ts"]) {
      const src = read(f);
      const at = src.indexOf("body: JSON.stringify(bodyObj)");
      expect(at, f).toBeGreaterThanOrEqual(0);
      expect(src.slice(at - 300, at + 300), f).toMatch(/fetch\(url, \{[\s\S]{0,300}?redirect:\s*"manual"/);
    }
  });

  it("nothing that sends customer data asks to follow redirects", () => {
    const follow = files(FUNCTIONS, (n) => n.endsWith(".ts") && !n.endsWith("_test.ts"))
      .filter((f) => /redirect:\s*"follow"/.test(code(readFileSync(f, "utf8"))))
      .map((f) => f.slice(ROOT.length + 1));
    // integration-account-search only looks up public profiles on fixed sites (GitHub and the like) and sends nothing of the customer's.
    expect(follow).toEqual(["supabase/functions/integration-account-search/index.ts"]);
  });
});

describe("pages read from a typed-in address use the https-only fetch", () => {
  it.each([
    ["supabase/functions/business-context-researcher/index.ts", 1],
    ["supabase/functions/agent-runtime/index.ts", 2],
    ["supabase/functions/analyze-inputs/index.ts", 1],
  ])("%s", (file, calls) => {
    expect(code(read(file)).match(/fetchPublicHttps\(/g)?.length ?? 0).toBeGreaterThanOrEqual(calls);
  });
});

describe("the two hosting setups send the same security headers", () => {
  const vercel = JSON.parse(read("vercel.json")) as { headers: { source: string; headers: { key: string; value: string }[] }[] };
  const netlify: Record<string, Record<string, string>> = {};
  let path = "";
  for (const line of read("public/_headers").split("\n")) {
    if (!line.trim() || line.startsWith("#")) continue;
    if (!/^\s/.test(line)) { path = line.trim(); netlify[path] = {}; continue; }
    const i = line.indexOf(":");
    netlify[path][line.slice(0, i).trim()] = line.slice(i + 1).trim();
  }
  const fromVercel = (source: string) => Object.fromEntries(vercel.headers.find((h) => h.source === source)!.headers.map((h) => [h.key, h.value]));

  it("public/_headers (Netlify) matches vercel.json", () => {
    expect(netlify["/*"]).toEqual(fromVercel("/(.*)"));
    expect(netlify["/build-id.txt"]).toEqual(fromVercel("/build-id.txt"));
  });

  it("HTTPS is required for two years, subdomains included", () => {
    expect(fromVercel("/(.*)")["Strict-Transport-Security"]).toBe("max-age=63072000; includeSubDomains; preload");
  });

  it("the browser may only connect to https and wss addresses", () => {
    const csp = fromVercel("/(.*)")["Content-Security-Policy"];
    const connect = /connect-src ([^;]+);/.exec(csp)![1].trim().split(/\s+/);
    expect(connect.filter((s) => s !== "'self'" && !/^(https|wss):\/\/./.test(s))).toEqual([]);
    expect(csp).not.toMatch(/\bhttp:|\bws:/);
  });
});
