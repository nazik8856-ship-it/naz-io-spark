// Outer Control: one neutral shape for a result, used by every look (outer-control-templates.ts) and every file type
// (outer-control-files.ts). A report is turned into sections once, here; the looks and the files only decide how to draw them, so a
// Word file, a spreadsheet and a styled page can not disagree about what the result says. Pure, no dependencies.
import { composeReportText, fingerprint, KIND_BADGE, kindMethod, kindOf, REPORT_INTRO, VERDICT_LABEL, when, type ReportDoc, type ReportKind } from "@/lib/outer-control-report-doc";

export type Blk =
  | { k: "p"; text: string }
  | { k: "ul"; items: string[] }
  /** Words of a source, word for word, with where they came from. */
  | { k: "quote"; text: string; by: string }
  /** A version, option, step or part: its heading, who gave it, its text. */
  | { k: "item"; head: string; by: string; text: string }
  | { k: "table"; head: string[]; rows: string[][] };

/**
 * What a section is for, so a look can put them in its own order:
 *   bottom    the answer: conclusion, verdict, recommendation, final result
 *   summary   the short version, or what was given (the original text)
 *   points    what holds: agreements, key points, findings
 *   contrast  what does not: differences, open questions, corrections, risks
 *   detail    the working: versions, options, steps, the side-by-side
 *   sources   the tools' own answers, word for word
 *   method    how it was made
 */
export type SecKey = "bottom" | "summary" | "points" | "contrast" | "detail" | "sources" | "method";
export type Sec = { key: SecKey; title: string; blocks: Blk[] };
export type ResultDoc = { badge: string; title: string; meta: string; sections: Sec[]; footer: string };

export const FOOTER = "Generated by NazAI Outer Control";

const para = (text: string): Blk[] => (text.trim() ? [{ k: "p", text: text.trim() }] : []);
const list = (items: string[], empty: string): Blk => ({ k: "ul", items: items.length ? items : [empty] });

/** A report as sections. Mirrors what composeReportText and reportHtml say, kind by kind. */
export function reportToDoc(d: ReportDoc): ResultDoc {
  const kind: ReportKind = kindOf(d);
  const tool = (n: number) => d.opinions.find((o) => o.n === n)?.tool ?? "tool";
  const by = (n: number) => `${tool(n)} [${n}]`;
  const sources = (title: string): Sec => ({
    key: "sources", title,
    blocks: d.opinions.map((o) => ({
      k: "quote", text: o.text.trim() + (o.shortened ? "\n(Shortened for the report; the full controlled answer is stored in its step.)" : ""),
      by: `[${o.n}] ${o.tool} · received ${when(o.at)} · fingerprint ${fingerprint(o.sha256)}`,
    })),
  });
  const sections: Sec[] = [];
  const add = (key: SecKey, title: string, blocks: Blk[]) => { sections.push({ key, title, blocks }); };

  if (kind === "rewrite" || kind === "roles" || kind === "adapt") {
    add("summary", kind === "rewrite" ? "Original" : kind === "roles" ? "Question" : "Message", para(d.original ?? d.topic));
    const word = kind === "rewrite" ? "" : kind === "roles" ? "Role: " : "For: ";
    add("detail", kind === "rewrite" ? "Rewritten versions" : kind === "roles" ? "Answers by role" : "Adapted versions",
      (d.versions ?? []).map((v) => ({ k: "item", head: `${word}${v.style}`, by: by(v.n), text: v.text.trim() })));
  } else if (kind === "explain" || kind === "keypoints") {
    const n = d.opinions[0]?.n ?? 1;
    add("summary", "Original", para(d.original ?? d.topic));
    add("bottom", `${kind === "explain" ? "Simple explanation" : "Key points"} (by ${by(n)})`,
      kind === "explain" ? para(d.output ?? "") : [list(d.points ?? [], "No key points were given.")]);
  } else if (kind === "draft") {
    const [a, b] = [d.opinions[0], d.opinions[d.opinions.length - 1]];
    add("bottom", "Final version", para(d.output ?? ""));
    add("detail", "How it was drafted", para(`Drafted by ${a?.tool ?? "tool"} [${a?.n ?? 1}], improved by ${b?.tool ?? "tool"} [${b?.n ?? 2}]. The draft is kept in the Task's proof.`));
  } else if (kind === "alternatives" || kind === "multistep" || kind === "delegate") {
    const word = kind === "alternatives" ? "Option" : kind === "multistep" ? "Step" : "Part";
    if (kind !== "alternatives") add("summary", "Summary", para(d.summary));
    add("detail", kind === "alternatives" ? "Options" : kind === "multistep" ? "Steps" : "Parts",
      (d.items ?? []).map((it, i) => ({ k: "item", head: `${word} ${i + 1}: ${it.label}`, by: by(it.n), text: it.text.trim() })));
    if (kind !== "alternatives") add("bottom", kind === "multistep" ? "Solution" : "Final result", para(d.output ?? ""));
  } else if (kind === "decision") {
    const rows = (d.decision ?? []).map((o) => [o.option, (o.pros.length ? o.pros : ["None given."]).map((x) => `• ${x}`).join("\n"), (o.cons.length ? o.cons : ["None given."]).map((x) => `• ${x}`).join("\n")]);
    add("summary", "Summary", para(d.summary));
    add("detail", "Options", [{ k: "table", head: ["Option", "Pros", "Cons"], rows }]);
    add("bottom", "Recommendation", para(d.conclusion));
    add("contrast", "Risks", [list(d.risks ?? [], "No risks were named.")]);
    sections.push(sources("Answers by source"));
  } else if (kind === "research") {
    add("summary", "Summary", para(d.summary));
    add("points", "Key points", [list(d.points ?? [], "No key points were given.")]);
    add("contrast", "Open questions", [list(d.open_questions ?? [], "No open questions were named.")]);
    sections.push(sources("Answers by source"));
    add("bottom", "Conclusion", para(d.conclusion));
  } else if (kind === "factcheck") {
    add("bottom", "Verdict", [{ k: "p", text: VERDICT_LABEL[d.verdict ?? "cannot be verified"] }, ...para(d.summary)]);
    add("points", "Findings", [list(d.findings ?? [], "No findings were given.")]);
    add("contrast", "Corrections", [list(d.corrections ?? [], "No corrections were needed.")]);
    sections.push(sources("Answers by source"));
    add("bottom", "Conclusion", para(d.conclusion));
  } else if (kind === "compare") {
    add("summary", "Summary", para(d.summary));
    add("detail", "Side by side", [{
      k: "table", head: ["Aspect", ...d.opinions.map((o) => `[${o.n}] ${o.tool}`)],
      rows: (d.comparison ?? []).map((r) => [r.aspect, ...r.points]),
    }]);
    sections.push(sources("Answers by source"));
    add("points", "Where they agree", [list(d.agreements, "No shared points were identified.")]);
    add("contrast", "Where they differ", [list(d.differences, "No differences were identified.")]);
    add("bottom", "Conclusion", para(d.conclusion));
  } else {
    add("summary", "Summary", para(d.summary));
    sections.push(sources("Opinions by source"));
    add("points", "Where they agree", [list(d.agreements, "No shared points were identified.")]);
    add("contrast", "Where they differ", [list(d.differences, "No differences were identified.")]);
    add("bottom", "Conclusion", para(d.conclusion));
  }
  add("method", `How this ${kindOf(d) === "opinions" ? "report" : "result"} was made`, para(kindMethod(d)));
  return { badge: KIND_BADGE[kind], title: d.topic.replace(/\s+/g, " ").trim(), meta: REPORT_INTRO(d), sections, footer: FOOTER };
}

const LIST_LINE = /^\s*(?:[-*•]|\d{1,2}[.)])\s+(.*\S)\s*$/;
/** A heading line of a plain result: short, no lower-case letters ("SUMMARY", "WHERE THEY DIFFER"). */
const HEADING_LINE = /^[\p{Lu}\p{N}\s&/,:'’()–-]{3,60}$/u;

/** A result that is plain text (not a report): headed lines, bullet lines and paragraphs become sections and blocks. */
export function textToDoc(text: string, title: string, meta = ""): ResultDoc {
  const sections: Sec[] = [];
  let cur: Sec = { key: "detail", title: "", blocks: [] };
  const push = () => { if (cur.blocks.length || cur.title) sections.push(cur); };
  let bullets: string[] = [];
  let lines: string[] = [];
  const flushLines = () => { if (lines.length) cur.blocks.push({ k: "p", text: lines.join("\n") }); lines = []; };
  const flushBullets = () => { if (bullets.length) cur.blocks.push({ k: "ul", items: bullets }); bullets = []; };
  for (const raw of text.replace(/\r\n/g, "\n").split("\n")) {
    const line = raw.trimEnd();
    if (!line.trim()) { flushLines(); flushBullets(); continue; }
    if (HEADING_LINE.test(line.trim()) && /\p{L}/u.test(line)) { flushLines(); flushBullets(); push(); cur = { key: "detail", title: titleCase(line.trim()), blocks: [] }; continue; }
    const m = line.match(LIST_LINE);
    if (m) { flushLines(); bullets.push(m[1]); continue; }
    flushBullets(); lines.push(line);
  }
  flushLines(); flushBullets(); push();
  if (!sections.length) sections.push({ key: "detail", title: "", blocks: [{ k: "p", text: text.trim() }] });
  return { badge: "NAZAI RESULT", title: title.replace(/\s+/g, " ").trim().slice(0, 200) || "Result", meta, sections, footer: FOOTER };
}

const titleCase = (s: string) => s.toLowerCase().replace(/(^|\s)(\p{L})/gu, (_, a: string, b: string) => a + b.toUpperCase());

/** The result of a Task or a session as a document: its designed report while the stored text still is that report, else its plain text. */
export function artifactToDoc(a: { final_output: string; request?: string; objective?: string; report?: unknown; completed_at?: string }, isReport: (x: unknown) => x is ReportDoc): ResultDoc {
  const r = a.report;
  if (isReport(r) && composeReportText(r) === a.final_output) return reportToDoc(r);
  const meta = a.completed_at ? `Controlled result · ${when(a.completed_at)}. Every reply was checked against the account's rules before it was used.` : "";
  return textToDoc(a.final_output, a.request ?? a.objective ?? "Result", meta);
}

/** The sections in a look's order: the keys it lists first, in that order (a key may have several sections), then any it did not name. */
export function orderSections(doc: ResultDoc, order: readonly SecKey[]): Sec[] {
  const out: Sec[] = [];
  for (const key of order) for (const s of doc.sections) if (s.key === key) out.push(s);
  for (const s of doc.sections) if (!out.includes(s)) out.push(s);
  return out;
}
